import { chromium } from '../../../frontend/node_modules/playwright/index.mjs'
import { readFileSync, writeFileSync } from 'node:fs'
const dir = new URL('./', import.meta.url)
const auth = JSON.parse(readFileSync('/tmp/repaircalc-admin-recheck.json', 'utf8'))
const browser = await chromium.launch()
const page = await browser.newPage()
await page.goto('http://194.67.95.67/admin')
await page.getByLabel('Имя администратора').fill(auth.username)
await page.getByLabel('Пароль', { exact: true }).fill(auth.password)
await page.getByRole('button', { name: 'Войти', exact: true }).click()
await page.getByRole('link', { name: 'Новая карточка', exact: true }).waitFor()
const id = readFileSync(new URL('remote-workflow-id.txt', dir), 'utf8').trim()
await page.goto('http://194.67.95.67/admin/products/' + id)
await page.getByRole('button', { name: 'Загрузить задания и готовность' }).click()
await page.getByRole('button', { name: 'Обновить', exact: true }).waitFor()
await page.getByRole('button', { name: 'Проверить предложения' }).click()
writeFileSync(new URL('review-controls.txt', dir), await page.locator('.workflow form').ariaSnapshot())
writeFileSync(new URL('panel-current.txt', dir), await page.locator('.workflow').innerText())
await page.locator('.workflow').screenshot({ path: new URL('panel-current.png', dir).pathname })
console.log(await page.locator('.workflow').innerText())
await browser.close()
