import { test, expect } from '../../../frontend/node_modules/@playwright/test/index.js'
import { readFileSync } from 'node:fs'
import { join } from 'node:path'
test.use({ trace: 'off' })
test('published panel survives reload and restart; calculation remains available', async ({ page }, info) => {
  const auth = JSON.parse(readFileSync('/tmp/repaircalc-admin-recheck.json', 'utf8'))
  const dir = join(process.cwd(), 'reports/admin-workflow/2026-10-30-recheck')
  const id = readFileSync(join(dir, 'remote-workflow-id.txt'), 'utf8').trim()
  await page.goto('/admin')
  await page.getByLabel('Имя администратора').fill(auth.username)
  await page.getByLabel('Пароль', { exact: true }).fill(auth.password)
  await page.getByRole('button', { name: 'Войти', exact: true }).click()
  await expect(page.getByRole('link', { name: 'Новая карточка', exact: true })).toBeVisible()
  await page.goto('/admin/products/' + id)
  await page.getByRole('button', { name: 'Загрузить задания и готовность' }).click()
  await expect(page.getByRole('heading', { name: 'Готово к публикации и расчёту' })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Проверить предложения' })).toBeDisabled()
  await expect(page.getByRole('button', { name: 'Опубликовать снимок каталога и правил' })).toBeDisabled()
  await expect(page.getByRole('link', { name: 'Рассчитать опубликованный товар' })).toHaveAttribute('href', '/product?id=' + id)
  await page.getByText('Решения администратора (1)', { exact: true }).click()
  await expect(page.locator('.workflow details').last()).toContainText('paint-012-v1')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.getByText('Решения администратора (1)', { exact: true }).click()
  await page.locator('.workflow').screenshot({ path: join(dir, 'published-panel-' + info.project.name + '.png') })
  await page.getByRole('link', { name: 'Рассчитать опубликованный товар' }).click()
  await page.getByLabel('Добавить пояснение ИИ').uncheck()
  await page.getByRole('button', { name: 'Рассчитать упаковки' }).click()
  await expect(page.getByRole('heading', { name: 'Ваша смета готова' })).toBeVisible()
  await page.getByText('Как рассчитано').click()
  await expect(page.getByText('5,28 л', { exact: true })).toBeVisible()
  await expect(page.getByText(/3\s?703,50/).first()).toBeVisible()
})
